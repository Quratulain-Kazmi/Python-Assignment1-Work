import numpy as np
#array
a = np.array([1,2,3,4])
print(a)
#zero function    
a = np.zeros(5)
print(a)
#one function 
a = np.ones(5)
print(a)
#arrange function
a = np.arange(1,10)
print(a)
#random function
a = np.random.rand(5)
print(a)
#sum function
a = np.array([1,2,3,4])
print(np.sum(a))
#mean function
a = np.array([1,2,3,4])
print(np.mean(a))
#max and min function
a = np.array([5,2,9,1])

print(np.max(a))
print(np.min(a))

